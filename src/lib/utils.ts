// adds the peso sign and commas, ex: 12201 -> ₱12,201
export function formatPeso(amount: number) {
  return "₱" + amount.toLocaleString("en-PH");
}

// same thing but always 2 decimals, ex: 350 -> ₱350.00
export function formatPesoDecimals(amount: number) {
  return (
    "₱" +
    amount.toLocaleString("en-PH", {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    })
  );
}

// relative time, ex: "10 minutes ago", "yesterday"
export function timeAgo(date: string | Date, now: Date = new Date()) {
  const seconds = Math.round((new Date(date).getTime() - now.getTime()) / 1000);
  const rtf = new Intl.RelativeTimeFormat("en", { numeric: "auto" });
  const units: [Intl.RelativeTimeFormatUnit, number][] = [
    ["year", 31536000],
    ["month", 2592000],
    ["week", 604800],
    ["day", 86400],
    ["hour", 3600],
    ["minute", 60],
  ];
  for (const [unit, size] of units) {
    if (Math.abs(seconds) >= size) return rtf.format(Math.round(seconds / size), unit);
  }
  return "just now";
}
